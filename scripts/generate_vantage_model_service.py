#!/usr/bin/env python3
"""Generate provider Go transport structs from the single owner OpenAPI."""
import json
import re
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'pkg/vantagequota/model-service-2.openapi.json'
schemas = json.loads(source.read_text())['components']['schemas']

def go_type(schema):
    if '$ref' in schema:
        result = schema['$ref'].split('/')[-1]
    elif schema['type'] == 'array':
        result = '[]' + go_type(schema['items'])
    else:
        result = {'string': 'string', 'integer': 'int64', 'boolean': 'bool'}[schema['type']]
    return '*' + result if schema.get('nullable') else result

lines = ['// Code generated by scripts/generate_vantage_model_service.py; DO NOT EDIT.',
         'package vantagequota', '']
for name, schema in schemas.items():
    lines.append('type ' + name + ' struct {')
    for field, value in schema['properties'].items():
        identifier = ''.join(p.title() for p in field.split('_'))
        lines.append(f'\t{identifier} {go_type(value)} `json:"{field}"`')
    lines.extend(['}', ''])
out = root / 'pkg/vantagequota/model_service_generated.go'
source = subprocess.run(['gofmt'], input='\n'.join(lines), text=True, capture_output=True, check=True).stdout
import sys
if '--check' in sys.argv:
    if out.read_text() != source:
        raise SystemExit('model-service-2 generated Go contract drift')
else:
    out.write_text(source)
